def create_pyg_graph(cartesian_coordinates_tensor, atomic_numbers_tensor, r=2.5):
    """Creates a PyTorch Geometric graph."""
    if 'torch_cluster' not in sys.modules:
        return None # Skip if dependencies missing
    from torch_cluster import radius_graph
    from torch_geometric.data import Data
    
    edge_index = radius_graph(cartesian_coordinates_tensor, r=r)
    data = Data(x=atomic_numbers_tensor.view(-1, 1).float(), 
                pos=cartesian_coordinates_tensor, 
                edge_index=edge_index)
    return data

def correct_edges(data, scale_factor=1.3):
    """Corrects edges based on covalent radii."""
    if data is None: return None
    from ase.data import covalent_radii

    atomic_nums = data.x.view(-1).int().tolist()
    edge_index = data.edge_index
    valid_edges = []
    
    for node in range(len(atomic_nums)):
        adjacent_nodes = edge_index[1][edge_index[0] == node].tolist()
        for adj_node in adjacent_nodes:
            bond_length = torch.norm(data.pos[node] - data.pos[adj_node]).item()
            r1 = covalent_radii[atomic_nums[node]] * scale_factor
            r2 = covalent_radii[atomic_nums[adj_node]] * scale_factor
            if bond_length <= r1 + r2:
                valid_edges.append([node, adj_node])
                
    data.edge_index = torch.tensor(valid_edges, dtype=torch.long).t().contiguous()
    return data

def get_num_graphs(data):
    """Calculates number of connected components."""
    if data is None: return -1
    if data.edge_index.numel() == 0: return data.num_nodes
    g = to_networkx(data, to_undirected=True)
    return nx.number_connected_components(g)

def augment_distortion(
    input_source: Path, # dir or db
    output_target: Path, # dir or db
    sigma: float = 0.1, # d_max in original script
    fraction: float = 1.0,
    is_db_mode: bool = None,
    freeze_indices: List[int] = None
):
    """
    Applies random distortion to atomic coordinates.
    Also calculates graph connectivity.
    """
    d_max = sigma # Renaming to match original logic
    
    input_path = Path(input_source)
    if is_db_mode is None:
         is_db_mode = input_path.suffix == '.db'
         if is_db_mode:
             logger.info(f"Auto-detected DB mode from input: {input_path}")
         elif input_path.is_dir():
             logger.info(f"Auto-detected XYZ mode from input directory: {input_path}")
         else:
             # Fallback or error if ambiguous? 
             # If it's a file but not .db, it might be an XYZ file, but the logic below assumes dir for XYZ.
             # Original logic: input_dir.glob("*.xyz")
             pass
    
    if is_db_mode:
        db_path = Path(input_source)
        output_db_path = Path(output_target)
        
        db = connect(str(db_path))
        output_db = connect(str(output_db_path))
        num_entries = len(db)
        
        for row in tqdm(db.select(), total=num_entries, desc="Distorting molecules"):
            try:
                atoms = row.toatoms()
                coords = torch.tensor(atoms.get_positions(), dtype=torch.float32)
                
                d = random.uniform(0, d_max)
                offsets = (torch.rand_like(coords) * 2 - 1) * d
                
                if freeze_indices:
                     mask = torch.ones_like(coords)
                     valid_indices = [i for i in freeze_indices if i < len(coords)]
                     if valid_indices:
                         mask[valid_indices] = 0.0
                     offsets = offsets * mask
                     
                new_coords = coords + offsets
                
                distorted_atoms = atoms.copy()
                distorted_atoms.set_positions(new_coords.numpy())
                
                # Connectivity check
                num_graphs = -1
                if 'torch_geometric' in sys.modules:
                    z = torch.tensor(atoms.get_atomic_numbers(), dtype=torch.long)
                    data = create_pyg_graph(new_coords, z)
                    data = correct_edges(data)
                    num_graphs = get_num_graphs(data)

                new_data = row.data.copy()
                new_data['original_id'] = row.id
                new_data['distortion_d'] = d
                new_data['num_graph'] = num_graphs
                
                # We keep existing KVPs but ensures new ones go to 'data'
                output_db.write(atoms=distorted_atoms, key_value_pairs=row.key_value_pairs, data=new_data)
                
            except Exception as e:
                logger.error(f"Failed to process row {row.id}: {e}")
                
    else:
        # XYZ Mode
        input_dir = Path(input_source)
        output_dir = Path(output_target)
        output_dir.mkdir(exist_ok=True)
        
        files = sorted(list(input_dir.glob("*.xyz")))
        
        records = []
        for f in tqdm(files, desc="Distorting XYZs"):
            try:
                atoms, coords = read_xyz(f)
                coords = torch.tensor(coords, dtype=torch.float32)
                
                d = random.uniform(0, d_max)
                offsets = (torch.rand_like(coords) * 2 - 1) * d
                
                if freeze_indices:
                     mask = torch.ones_like(coords)
                     valid_indices = [i for i in freeze_indices if i < len(coords)]
                     if valid_indices:
                         mask[valid_indices] = 0.0
                     offsets = offsets * mask

                new_coords = coords + offsets
                
                # Connectivity check
                num_graphs = -1
                if 'torch_geometric' in sys.modules:
                    z = torch.tensor(symbols2numbers(atoms), dtype=torch.long)
                    data = create_pyg_graph(new_coords, z)
                    data = correct_edges(data)
                    num_graphs = get_num_graphs(data)
                
                out_name = f"{f.stem}_{d:.4f}.xyz"
                write_xyz(output_dir / out_name, atoms, new_coords.numpy())
                
                records.append({
                    'original': f.name,
                    'new': out_name,
                    'd': d,
                    'num_graphs': num_graphs
                })
            except Exception as e:
                logger.error(f"Failed {f}: {e}")
                
        # Save CSV
        import csv
        with open(output_dir / 'distortion_data.csv', 'w') as f:
            writer = csv.DictWriter(f, fieldnames=['original', 'new', 'd', 'num_graphs'])
            writer.writeheader()
            writer.writerows(records)


# --- Augmentation Logic: Size ---

from scipy.spatial.transform import Rotation
from collections import defaultdict
import math

def get_target_count(s, s_start, t_start, s_end, t_end, decay_power=1.0):
    if s < s_start: return t_start
    if s > s_end: return t_end
    
    if t_start <= 0 or t_end <= 0:
        return t_start + (t_end - t_start) * (s - s_start) / (s_end - s_start)
        
    log_t_start = math.log(t_start)
    log_t_end = math.log(t_end)
    interp = ((s - s_start) / (s_end - s_start)) ** (1.0 / decay_power)
    return math.exp(log_t_start + (log_t_end - log_t_start) * interp)

def augment_size(
    input_db: Path,
    output_db: Path,
    s_start: int, t_start: int,
    s_end: int, t_end: int,
    strength: float = 1.0,
    decay_power: float = 1.0,
    invert_prob: float = 0.5,
    plot_prefix: Path = None
):
    """
    Augments DB by adding rotated/inverted versions to balance molecule sizes.
    """
    from MolecularDiffusion.utils import plot_function as pf
    import matplotlib.pyplot as plt

    db = connect(str(input_db))
    counts = defaultdict(int)
    total = len(db)
    
    # Phase 1: Count
    for row in tqdm(db.select(), total=total, desc="Scanning sizes"):
        counts[row.natoms] += 1
        
    # Phase 2: Calculate Factors
    factors = {}
    for s in sorted(counts.keys()):
        if s_start <= s <= s_end:
            n_s = counts[s]
            if n_s == 0: continue
            
            t_s = get_target_count(s, s_start, t_start, s_end, t_end, decay_power)
            needed = (t_s - n_s) * strength
            target = n_s + needed
            
            if target > n_s:
                factor = math.floor(target / n_s) - 1
                if factor > 0: factors[s] = factor

    # Phase 3: Augment
    output_db = Path(output_db)
    if output_db.exists():
        logger.warning(f"Output DB {output_db} exists. Appending...")
        
    new_db = connect(str(output_db))
    
    if not factors:
        logger.info("No augmentation needed. Copying...")
        for row in tqdm(db.select(), total=total, desc="Copying"):
             new_db.write(row.toatoms(), key_value_pairs=row.key_value_pairs, data=row.data)
    else:
        for row in tqdm(db.select(), total=total, desc="Augmenting"):
            # Write original
            new_db.write(row.toatoms(), key_value_pairs=row.key_value_pairs, data=row.data)
            
            s = row.natoms
            if s in factors:
                factor = factors[s]
                atoms = row.toatoms()
                pos = atoms.get_positions()
                center = np.mean(pos, axis=0)
                pos -= center
                
                for _ in range(factor):
                    new_pos = pos.copy()
                    
                    # Random rotation
                    rot = Rotation.random().as_matrix()
                    new_pos = new_pos @ rot.T
                    
                    # Inversion
                    if random.random() < invert_prob:
                        new_pos *= -1.0
                        
                    new_pos += center
                    aug_atoms = atoms.copy()
                    aug_atoms.set_positions(new_pos)
                    
                    new_db.write(aug_atoms, key_value_pairs=row.key_value_pairs.copy(), data=row.data.copy())

    logger.info(f"Augmentation complete. New size: {len(new_db)}")
    
    # Plotting
    if plot_prefix:
        plot_prefix = str(plot_prefix)
        sizes = [row.natoms for row in new_db.select()]
        sizes = np.array(sizes)
        try:
             Path(plot_prefix).parent.mkdir(parents=True, exist_ok=True)
             pf.plot_histogram_distribution(sizes, task_name="num_atoms_augmented", output_path=f"{plot_prefix}_hist.png")
             pf.plot_kde_distribution(sizes, task_name="num_atoms_augmented", output_path=f"{plot_prefix}_kde.png")
        except Exception as e:
            logger.error(f"Failed to plot sizes: {e}")


