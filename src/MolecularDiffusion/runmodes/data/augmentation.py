# --- Chemistry Helpers ---

def get_electronegativity(element_symbol):
    try:
        return element(element_symbol).en_pauling
    except Exception:
        logger.error(f"Could not retrieve electronegativity for {element_symbol}")
        raise

def read_xyz(filename) -> Tuple[List[str], np.ndarray]:
    with open(filename, 'r') as f:
        lines = f.readlines()
    atom_count = int(lines[0])
    atoms = []
    coords = []
    for line in lines[2:2 + atom_count]:
        parts = line.split()
        atoms.append(parts[0])
        coords.append([float(x) for x in parts[1:4]])
    return atoms, np.array(coords)

def write_xyz(filename, atoms, coords):
    with open(filename, 'w') as f:
        f.write(f"{len(atoms)}\nGenerated by augmentation\n")
        for atom, coord in zip(atoms, coords):
            f.write(f"{atom} {coord[0]:.6f} {coord[1]:.6f} {coord[2]:.6f}\n")

# --- Augmentation Logic: Random Charge ---

def add_h_unit(atoms: List[str], coords: np.ndarray) -> Optional[Tuple[List[str], np.ndarray, int]]:
    """Adds a single hydrogen to a non-halogen heteroatom."""
    halogens = ['F', 'Cl', 'Br', 'I']
    heteroatom_indices = [i for i, atom in enumerate(atoms) 
                          if atom not in ['C', 'H'] and atom not in halogens]

    if not heteroatom_indices:
        return None

    # Pick random heteroatom
    idx = random.choice(heteroatom_indices)
    coord = coords[idx]
    elem = atoms[idx]

    # Find non-clashing position
    new_h_coord = None
    for _ in range(50):
        vec = np.random.randn(3)
        vec /= np.linalg.norm(vec)
        proposed = coord + vec * 1.0 # 1.0 Angstrom distance
        
        # Simple clash check
        dists = np.linalg.norm(coords - proposed, axis=1)
        if np.min(dists) >= 0.8:
            new_h_coord = proposed
            break
            
    if new_h_coord is None:
        return None

    new_atoms = list(atoms) + ['H']
    new_coords = np.vstack([coords, new_h_coord])
    
    # Charge logic: If heteroatom is more EN than H, adding H increases charge?
    # Original logic: limit charge increment
    charge_inc = 1 if get_electronegativity(elem) > get_electronegativity('H') else -1
    return new_atoms, new_coords, charge_inc

def remove_h_unit(atoms: List[str], coords: np.ndarray) -> Optional[Tuple[List[str], np.ndarray, int]]:
    """Removes a single hydrogen."""
    h_indices = [i for i, atom in enumerate(atoms) if atom == 'H']
    if not h_indices: return None
    
    idx = random.choice(h_indices)
    h_coord = coords[idx]
    
    # Find bonded atom
    dists = np.linalg.norm(coords - h_coord, axis=1)
    dists[idx] = float('inf') # Ignore self
    bonded_idx = np.argmin(dists)
    
    elem = atoms[bonded_idx]
    charge_inc = -1 if get_electronegativity(elem) > get_electronegativity('H') else 1
    
    new_atoms = [atom for i, atom in enumerate(atoms) if i != idx]
    new_coords = np.delete(coords, idx, axis=0)
    
    return new_atoms, new_coords, charge_inc

