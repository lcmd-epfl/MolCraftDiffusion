def test_adaln_zero_denses_are_zero_initialized():
    """Every adaLN-Zero Dense starts at exactly zero.

    A loaded checkpoint would hide a mistake here; training from scratch would
    not. The zero-init modules are: each DiT block's modulation Dense, and the
    readout's. ``MLP(output_is_zero_at_init=True)`` in
    ``RadialSphericalEdgeEmbedding`` is checked too.
    """
    for variant in ("ape", "rpe", "so3"):
        model = _build(variant)
        for layer in model.layers:
            assert layer.ada_dense.weight.abs().max().item() == 0.0, variant
            assert layer.ada_dense.bias.abs().max().item() == 0.0, variant
        assert model.readout.ada_dense.weight.abs().max().item() == 0.0, variant
        if variant == "so3":
            last = model.edge_embedding.hops_mlp.layers[-1]
            assert last.weight.abs().max().item() == 0.0


def test_so3_drift_is_exactly_zero_at_init():
    """adaLN-Zero leaves dit_so3 with no l=1 signal at all at init.

    Exactly 0.0, not small: the equivariant readout reads only the ``l=1``
    block, and every residual branch that could populate it is gated by a
    zero-initialized alpha. ``dit_ape``/``dit_rpe`` are deliberately NOT
    included -- their readout head maps the (non-zero) invariant node features
    straight to a drift, so theirs is non-zero at init by construction.
    """
    latent, cond = _toy_graphs()
    t = torch.full((latent.num_nodes,), 0.3, dtype=DTYPE)
    drift, noise = _build("so3")(time_latent=t, graph_latent=latent, graph_cond=cond)
    assert drift.abs().max().item() == 0.0
    assert noise.abs().max().item() == 0.0


def _randomize_zero_init(model):
    with torch.no_grad():
        for p in model.parameters():
            if p.abs().max() == 0:
                p.normal_(0, 0.3)
    return model


def test_dit_so3_forward_is_so3_equivariant():
    """The single strongest end-to-end offline check."""
    latent, cond = _toy_graphs()
    t = torch.full((latent.num_nodes,), 0.37, dtype=DTYPE)
    model = _randomize_zero_init(_build("so3"))
    drift, _ = model(time_latent=t, graph_latent=latent, graph_cond=cond)
    assert drift.abs().max() > 1e-3, "test is vacuous if the drift is zero"
    rot = e3x.random_rotation(1, dtype=DTYPE)[0]
    drift_r, _ = model(
        time_latent=t,
        graph_latent=latent.replace(positions=latent.positions @ rot.T),
        graph_cond=cond,
    )
    assert torch.allclose(drift_r, drift @ rot.T, atol=1e-10), (
        (drift_r - drift @ rot.T).abs().max()
    )


