def test_self_attention_is_so3_equivariant():
    """Rotating the geometry rotates the l=1 block and leaves l=0 invariant."""
    torch.manual_seed(9)
    n, f, nb = 6, 16, 8
    sa = SelfAttention(
        in_features=f,
        in_max_degree=0,
        in_num_parity=1,
        num_heads=4,
        max_degree=1,
        include_pseudotensors=True,
        num_basis=nb,
        basis_max_degree=1,
        basis_num_parity=1,
    ).to(DTYPE)
    x = torch.randn(n, 1, 1, f, dtype=DTYPE)
    pos = torch.randn(n, 3, dtype=DTYPE)
    dst, src = _self_edges(n)

    def run(p):
        b = e3x.basis(
            p[src] - p[dst],
            max_degree=1,
            num=nb,
            radial_fn=e3x.reciprocal_bernstein,
            cutoff_fn=None,
        )
        return sa(x, b, dst_idx=dst, src_idx=src, num_segments=n)

    out = run(pos)
    rot = e3x.random_rotation(1, dtype=DTYPE)[0]
    out_r = run(pos @ rot.T)
    assert torch.allclose(out_r[..., 0, :], out[..., 0, :], atol=1e-10)
    vec = out[..., 1:4, :]
    vec_r = out_r[..., 1:4, :]
    assert torch.allclose(vec_r, torch.einsum("ij,npjf->npif", rot, vec), atol=1e-10)


def test_equivariant_layer_norm():
    torch.manual_seed(10)
    # At P=1, L=0 it is a plain LayerNorm.
    ln = EquivariantLayerNorm(8, 0, 1).to(DTYPE)
    x = torch.randn(5, 1, 1, 8, dtype=DTYPE)
    ref = torch.nn.functional.layer_norm(x, (8,), ln.norm00.weight, ln.norm00.bias, 1e-6)
    assert torch.allclose(ln(x), ref, atol=1e-12)

    # At L=1 the l>0 scaling is rotation invariant.
    ln1 = EquivariantLayerNorm(8, 1, 1, use_scale=False, use_bias=False).to(DTYPE)
    y = torch.randn(5, 1, 4, 8, dtype=DTYPE)
    rot = e3x.random_rotation(1, dtype=DTYPE)[0]
    y_r = y.clone()
    y_r[:, 0, 1:4, :] = torch.einsum("ij,njf->nif", rot, y[:, 0, 1:4, :])
    out, out_r = ln1(y), ln1(y_r)
    assert torch.allclose(out[:, 0, 0], out_r[:, 0, 0], atol=1e-11)
    assert torch.allclose(
        torch.einsum("ij,njf->nif", rot, out[:, 0, 1:4]), out_r[:, 0, 1:4], atol=1e-11
    )


