def test_spherical_harmonics_hard_coded_ground_truth():
    """The plan's literal ground truth for a unit vector ``(x, y, z)``.

    Degree 1 must be ``(x, y, z)`` -- Cartesian order ``m = +l, -l, ..., 0``.
    An m-ascending convention (e3nn's) would give ``(y, z, x)``.
    """
    torch.manual_seed(0)
    r = torch.randn(128, 3, dtype=DTYPE)
    u = r / r.norm(dim=-1, keepdim=True)
    y = e3x.spherical_harmonics(u, 2)
    x, yy, z = u[:, 0], u[:, 1], u[:, 2]
    expect = torch.stack(
        [
            torch.ones_like(x),
            x,
            yy,
            z,
            math.sqrt(3) / 2 * (x**2 - yy**2),
            math.sqrt(3) * x * yy,
            math.sqrt(3) * x * z,
            math.sqrt(3) * yy * z,
            (3 * z**2 - 1) / 2,
        ],
        dim=-1,
    )
    assert torch.allclose(y, expect, atol=1e-12)


