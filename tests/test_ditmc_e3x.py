def test_cfg_scaling_gates_exactly_what_upstream_gates():
    """``cond_scaling = 0`` gates the conditioner and the shortest-hops term.

    Which pieces survive is variant-specific and worth pinning, because it is
    not symmetric:

    * ``ape`` -- the edge embedding has NO displacement term, so gating the
      hops term leaves it identically zero.
    * ``rpe`` -- the displacement MLP is ungated, so the edge embedding stays
      non-zero.
    * ``so3`` -- the spherical basis is ungated; only the learned hops
      scaling is gated.

    Note also the readout quirk this reproduces: neither ``SimpleReadout`` nor
    ``EquivariantReadout`` applies ``cond_scaling``, so the conditioner
    features reach the readout unscaled even when every DiT block has them
    zeroed. That is upstream behaviour, quirk and all.
    """
    latent, cond = _toy_graphs()
    e = latent.senders.shape[0]
    off = latent.replace(
        cond_scaling_nodes=torch.zeros(latent.num_nodes, dtype=DTYPE),
        cond_scaling_edges=torch.zeros(e, dtype=DTYPE),
    )
    expect_zero = {"ape": True, "rpe": False, "so3": False}
    for variant in ("ape", "rpe", "so3"):
        model = _randomize_zero_init(_build(variant))
        on = model.edge_embedding(latent)
        gated = model.edge_embedding(off)
        assert not torch.allclose(on, gated), variant
        if expect_zero[variant]:
            assert gated.abs().max().item() == 0.0, variant
        else:
            assert gated.abs().max().item() > 0.0, variant

        t = torch.full((latent.num_nodes,), 0.4, dtype=DTYPE)
        d_on, _ = model(time_latent=t, graph_latent=latent, graph_cond=cond)
        d_off, _ = model(time_latent=t, graph_latent=off, graph_cond=cond)
        assert not torch.allclose(d_on, d_off, atol=1e-6), variant


def test_guidance_scale_one_reproduces_the_unguided_update():
    """CFG at scale 1.0 must be a bit-for-bit no-op."""
    latent, cond = _toy_graphs()
    prior = HarmonicPrior()
    n = latent.num_nodes
    i, j = torch.meshgrid(torch.arange(n), torch.arange(n), indexing="ij")
    graph_prior = PriorGraph(
        node_attr=torch.ones(n, dtype=DTYPE),
        senders=j.reshape(-1),
        receivers=i.reshape(-1),
        edge_attr=torch.eye(n, dtype=DTYPE).reshape(-1),
    )
    model = _randomize_zero_init(_build("so3"))

    def run(free_guidance):
        fm = FlowMatching(prior=prior, free_guidance_bool=free_guidance)
        g = torch.Generator().manual_seed(3)
        out = fm.sample(
            model, latent, graph_prior, cond, num_steps=3, generator=g,
            free_guidance_scale=1.0,
        )
        return out.positions

    assert torch.allclose(run(False), run(True), atol=1e-11)


def test_self_conditioning_starts_from_zeros_and_does_not_leak_gradient():
    latent, cond = _toy_graphs()
    model = _build("so3", self_conditioning=True)
    emb = model.node_embedding
    assert emb.sc_mlp is not None
    zeros = latent.replace(self_cond=torch.zeros(latent.num_nodes, 3, dtype=DTYPE))
    # step 0 uses zeros: passing None must be identical to passing zeros.
    assert torch.allclose(emb(latent), emb(zeros), atol=1e-12)
    # the MLP is bias-free, so a zero self_cond contributes exactly nothing
    assert all(layer.bias is None for layer in emb.sc_mlp.layers)


