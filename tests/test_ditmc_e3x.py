def test_shortest_hops_match_scipy_and_the_edge_order():
    scipy_csgraph = pytest.importorskip("scipy.sparse.csgraph")
    rng = np.random.default_rng(0)
    for n in (2, 5, 9):
        adj = (rng.random((n, n)) < 0.35).astype(np.int64)
        adj = np.triu(adj, 1)
        adj = adj + adj.T
        hops = shortest_hops_from_adjacency(adj)
        dist = scipy_csgraph.floyd_warshall(
            adj.astype(float), directed=False, unweighted=True
        )
        rec, sen = all_pairs_edges(n)
        assert len(hops) == n * (n - 1)
        for k in range(len(hops)):
            ref = dist[rec[k], sen[k]]
            ref = UNREACHABLE_HOPS if np.isinf(ref) else ref
            assert hops[k] == ref, (n, k)


def test_harmonic_prior_covariance_is_the_laplacian_pseudoinverse():
    adj = np.array(
        [[0, 1, 0, 0], [1, 0, 1, 0], [0, 1, 0, 1], [0, 0, 1, 0]], dtype=np.int64
    )
    d, p = laplacian_eigen(adj, num_components=1)
    n = 4
    i, j = torch.meshgrid(torch.arange(n), torch.arange(n), indexing="ij")
    graph = PriorGraph(
        node_attr=torch.as_tensor(d),
        senders=j.reshape(-1),
        receivers=i.reshape(-1),
        edge_attr=torch.as_tensor(p).reshape(-1),
    )
    g = torch.Generator().manual_seed(0)
    s = torch.stack(
        [HarmonicPrior().sample((n, 3), graph, generator=g) for _ in range(20000)]
    )
    cov = torch.einsum("sid,sjd->ij", s, s) / (s.shape[0] * 3)
    lap = np.diag(adj.sum(1)) - adj
    expect = torch.as_tensor(np.linalg.pinv(lap.astype(float)), dtype=torch.float32)
    assert torch.allclose(cov, expect, atol=0.08)
    # The lambda=0 mode is zeroed, which is what removes the COM.
    assert s.mean(dim=1).abs().max() < 1e-4


