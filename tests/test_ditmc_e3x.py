def test_gated_gelu_matches_tanh_approximation():
    """``e3x.nn.gelu`` on a scalar input is elementwise ``gelu(tanh)``."""
    torch.manual_seed(5)
    x = torch.randn(9, 1, 1, 6, dtype=DTYPE)
    got = e3x.gelu(x)
    ref = torch.nn.functional.gelu(x, approximate="tanh")
    assert torch.allclose(got, ref, atol=1e-12)
    # NOT the exact erf form -- that is the trap.
    assert not torch.allclose(got, torch.nn.functional.gelu(x), atol=1e-6)

    # On an L=1 input the l=1 block is scaled by the l=0-derived gate.
    y = torch.randn(9, 1, 4, 6, dtype=DTYPE)
    gated = e3x.gelu(y)
    gate = gated[:, 0:1, 0:1, :] / y[:, 0:1, 0:1, :]
    assert torch.allclose(gated[:, :, 1:4, :], gate * y[:, :, 1:4, :], atol=1e-12)


