def _self_edges(n: int):
    return all_pairs_edges(n)


def test_self_attention_reduces_to_plain_mha():
    """Pins ``1/sqrt(depth)`` and the ``f % num_heads`` q/k head fold."""
    torch.manual_seed(7)
    n, f, h = 6, 16, 4
    sa = SelfAttention(
        in_features=f,
        in_max_degree=0,
        in_num_parity=1,
        num_heads=h,
        max_degree=0,
        include_pseudotensors=False,
        use_relative_positional_encoding_qk=False,
        use_relative_positional_encoding_v=False,
    ).to(DTYPE)
    x = torch.randn(n, 1, 1, f, dtype=DTYPE)
    dst, src = _self_edges(n)
    out = sa(x, None, dst_idx=dst, src_idx=src, num_segments=n)

    q = sa.query(x).squeeze(1).squeeze(1)
    k = sa.key(x).squeeze(1).squeeze(1)
    v = sa.value(x).squeeze(1).squeeze(1)
    hd = f // h
    qh = q.reshape(n, hd, h).permute(2, 0, 1)
    kh = k.reshape(n, hd, h).permute(2, 0, 1)
    logits = (qh @ kh.transpose(1, 2)) / math.sqrt(hd)
    logits = logits.masked_fill(torch.eye(n, dtype=torch.bool), float("-inf"))
    w = torch.softmax(logits, dim=-1)
    # value feature f is weighted by head f // head_dim -- the OTHER fold
    vg = v.reshape(n, h, hd)
    ref = sa.out(torch.einsum("hij,jhd->ihd", w, vg).reshape(n, f)[:, None, None, :])
    assert torch.allclose(out, ref, atol=1e-11), (out - ref).abs().max()


