def test_clebsch_gordan_identity_and_selection_rule():
    cg = e3x.clebsch_gordan(1, 1, 1, dtype=DTYPE)
    assert cg[0, 0, 0].item() == pytest.approx(1.0, abs=1e-12)
    cg2 = e3x.clebsch_gordan(2, 2, 2, dtype=DTYPE)
    # Zero wherever the triangle rule is violated.
    for l1 in range(3):
        for l2 in range(3):
            for l3 in range(3):
                if not abs(l1 - l2) <= l3 <= l1 + l2:
                    block = cg2[
                        l1**2 : (l1 + 1) ** 2,
                        l2**2 : (l2 + 1) ** 2,
                        l3**2 : (l3 + 1) ** 2,
                    ]
                    assert block.abs().max().item() == pytest.approx(0.0, abs=1e-12)


def _e3x_symbolic_module():
    """Load the vendored e3x SymPy generator from the reference cache."""
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(
        here,
        "..",
        "docs",
        "model_integrations",
        "ditmc",
        "reference",
        "e3x_source",
        "so3",
        "_symbolic.py",
    )
    path = os.path.realpath(path)
    if not os.path.exists(path):
        pytest.skip(f"e3x reference source not present at {path}")
    spec = importlib.util.spec_from_file_location("_e3x_symbolic", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def test_tables_match_e3x_own_generator():
    """Re-run e3x's generator and compare EXACTLY, not approximately."""
    sympy = pytest.importorskip("sympy")
    sym = _e3x_symbolic_module()

    # Spherical harmonics: evaluate e3x's symbolic polynomial and the port at
    # the same random points.
    torch.manual_seed(1)
    r = torch.randn(24, 3, dtype=DTYPE)
    u = (r / r.norm(dim=-1, keepdim=True)).numpy()
    ours = e3x.spherical_harmonics(torch.as_tensor(u), 2).numpy()

    x, y, z = sympy.symbols("x y z")
    for l in range(3):  # noqa: E741
        perm = e3x.cartesian_permutation_for_degree(l)
        for slot, m_idx in enumerate(perm):
            m = int(m_idx) - l
            poly = sym._spherical_harmonics(l, m)
            f = sympy.lambdify((x, y, z), poly.as_expr(), "numpy")
            ref = f(u[:, 0], u[:, 1], u[:, 2])
            ref = np.broadcast_to(np.asarray(ref, dtype=np.float64), (u.shape[0],))
            got = ours[:, l**2 + slot]
            assert np.allclose(got, ref, atol=1e-12), (l, m, np.abs(got - ref).max())

    # Clebsch-Gordan: regenerate and assert elementwise equality.
    ours_cg = e3x.clebsch_gordan(1, 1, 1, dtype=DTYPE).numpy()
    for l1 in range(2):
        for l2 in range(2):
            for l3 in range(2):
                p1 = e3x.cartesian_permutation_for_degree(l1)
                p2 = e3x.cartesian_permutation_for_degree(l2)
                p3 = e3x.cartesian_permutation_for_degree(l3)
                for a, ma in enumerate(p1):
                    for b, mb in enumerate(p2):
                        for c, mc in enumerate(p3):
                            ref = float(
                                sym._clebsch_gordan(
                                    l1, int(ma) - l1, l2, int(mb) - l2, l3, int(mc) - l3
                                )
                            )
                            got = ours_cg[l1**2 + a, l2**2 + b, l3**2 + c]
                            assert got == pytest.approx(ref, abs=1e-12), (
                                l1, l2, l3, a, b, c, got, ref,
                            )


def _fit_wigner_d(rot: torch.Tensor, degree: int) -> torch.Tensor:
    """Least-squares Wigner-D for one degree, from the ported SH themselves.

    ponytail: e3x's own ``wigner_d`` needs a second symbolic lookup table this
    port has no other use for. Fitting D from SH values at more points than
    unknowns is an equally strong check -- an inconsistent representation
    simply will not fit. Upgrade to the real table only if a future model needs
    ``wigner_d`` at runtime.
    """
    n = 2 * degree + 1
    u = torch.randn(64, 3, dtype=DTYPE)
    u = u / u.norm(dim=-1, keepdim=True)
    y = e3x.spherical_harmonics(u, degree)[:, degree**2 :]
    y_rot = e3x.spherical_harmonics(u @ rot.T, degree)[:, degree**2 :]
    d = torch.linalg.lstsq(y, y_rot).solution.T
    assert (y @ d.T - y_rot).abs().max() < 1e-9, "SH do not form a representation"
    assert d.shape == (n, n)
    return d


def test_spherical_harmonics_are_a_rotation_representation():
    torch.manual_seed(2)
    for _ in range(3):
        rot = e3x.random_rotation(1, dtype=DTYPE)[0]
        d1 = _fit_wigner_d(rot, 1)
        # Degree 1 in Cartesian order IS the rotation matrix.
        assert torch.allclose(d1, rot, atol=1e-9), (d1 - rot).abs().max()
        d2 = _fit_wigner_d(rot, 2)
        eye = torch.eye(5, dtype=DTYPE)
        assert torch.allclose(d2 @ d2.T, eye, atol=1e-8)


