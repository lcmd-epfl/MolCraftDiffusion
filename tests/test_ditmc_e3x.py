def test_add_and_change_max_degree_zero_fill():
    torch.manual_seed(3)
    for (p_in, l_in), (p_out, l_out) in [
        ((1, 0), (1, 1)),
        ((1, 0), (2, 1)),
        ((1, 1), (2, 1)),
        ((2, 1), (1, 1)),
        ((2, 1), (2, 0)),
    ]:
        x = torch.randn(5, p_in, (l_in + 1) ** 2, 7, dtype=DTYPE)
        y = e3x.change_max_degree_or_type(
            x, max_degree=l_out, include_pseudotensors=p_out == 2
        )
        assert y.shape == (5, p_out, (l_out + 1) ** 2, 7)
        if p_out == 2 and p_in == 1:
            # degree l lands only in the parity block l % 2; the rest is zero.
            for l in range(min(l_in, l_out) + 1):  # noqa: E741
                blk = y[:, 1 - l % 2, l**2 : (l + 1) ** 2, :]
                assert blk.abs().max() == 0

    a = torch.randn(5, 1, 1, 7, dtype=DTYPE)
    b = torch.randn(5, 2, 4, 7, dtype=DTYPE)
    s = e3x.add(a, b)
    assert s.shape == (5, 2, 4, 7)
    assert torch.allclose(s[:, 0, 0, :], a[:, 0, 0, :] + b[:, 0, 0, :])
    assert torch.allclose(s[:, 1, 0, :], b[:, 1, 0, :])  # a contributes nothing

    with pytest.raises(ValueError):
        e3x.add(a, torch.randn(5, 1, 1, 8, dtype=DTYPE))  # feature mismatch


