"""Tier-1 offline fidelity suite for the DiTMC port.

This is the **acceptance gate** for the integration, and it needs nothing
beyond what is already installed -- no jax, no flax, no e3x, no orbax.

The key enabler: e3x's spherical-harmonic and Clebsch-Gordan tables are
generated by pure SymPy (``so3/_symbolic.py`` imports only ``sympy`` and
``sympy.physics.wigner``), and SymPy is installed. So the ported tables are not
*approximated* -- :func:`test_tables_match_e3x_own_generator` re-runs e3x's own
generator and asserts elementwise equality.

What this suite does **not** cover, and cannot: bit-level parity against a
running JAX/Flax DiTMC, and reading the published Orbax checkpoints. Both need
an install that has not happened. Tier 1 proves the port is self-consistent and
mathematically correct; only Tier 2 proves it is *the same function* as
upstream.

Run::

    pytest tests/test_ditmc_e3x.py -q
"""

