def _toy_graphs(n=6, a=64, seed=11):
    torch.manual_seed(seed)
    dst, src = all_pairs_edges(n)
    e = src.shape[0]
    latent = LatentGraph(
        atomic_numbers=torch.tensor([6, 1, 1, 8, 1, 7]),
        node_attr=torch.randn(n, a, dtype=DTYPE),
        positions=torch.randn(n, 3, dtype=DTYPE),
        senders=src,
        receivers=dst,
        shortest_hops=torch.randint(0, 4, (e,)),
        batch_segments=torch.zeros(n, dtype=torch.long),
        num_graphs=1,
        cond_scaling_nodes=torch.ones(n, dtype=DTYPE),
        cond_scaling_edges=torch.ones(e, dtype=DTYPE),
    )
    cond = CondGraph(
        node_attr=latent.node_attr,
        senders=torch.tensor([0, 1, 0, 3]),
        receivers=torch.tensor([1, 0, 3, 0]),
        edge_attr=torch.eye(4, dtype=DTYPE),
    )
    return latent, cond


